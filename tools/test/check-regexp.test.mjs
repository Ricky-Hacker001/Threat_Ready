// node --test "tools/test/*.test.mjs" — exercises the ReDoS lint against the fixtures in tools/test/fixtures/regexp.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanSource, run } from '../check-regexp-from-input.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const fixtures = path.join(here, 'fixtures', 'regexp');
const read = (f) => fs.readFileSync(path.join(fixtures, f), 'utf8');

test('flags every marked line in flagged.ts and nothing else', () => {
  const src = read('flagged.ts');
  const expected = src.split('\n').map((l, i) => (l.includes('// FLAG') ? i + 1 : 0)).filter(Boolean);
  const got = scanSource(src).map((f) => f.line);
  assert.deepEqual([...new Set(got)].sort((a, b) => a - b), expected);
  const rules = Object.fromEntries(scanSource(src).map((f) => [f.line, f.rule]));
  for (const [line, rule] of Object.entries(rules)) {
    const marker = /FLAG (R\d)/.exec(src.split('\n')[line - 1]);
    assert.equal(rule, marker[1], `line ${line}`);
  }
});

test('reports nothing for clean.ts (literals, comments, strings, division)', () => {
  assert.deepEqual(scanSource(read('clean.ts')), []);
});

test('run(): exit 1 on findings, 0 when every finding is allowlisted, stale entries are only notes', () => {
  const logs = [], errs = [];
  const io = { cwd: here, log: (s) => logs.push(s), err: (s) => errs.push(s) };
  assert.equal(run(['--no-allowlist', 'fixtures/regexp/clean.ts'], io), 0);
  assert.equal(run(['--no-allowlist', 'fixtures/regexp/flagged.ts'], io), 1);
  assert.ok(errs.some((e) => /flagged\.ts:3: R1/.test(e)), 'file:line is printed');

  const flagged = scanSource(read('flagged.ts'));
  const rel = path.relative(path.resolve(here, '..', '..'), path.join(fixtures, 'flagged.ts')).split(path.sep).join('/');
  const allow = path.join(here, 'fixtures', 'regexp', '.allowlist.tmp');
  fs.writeFileSync(allow, ['# generated by the test', ...flagged.map((f) => `${rel}:${f.line}  test fixture`), `${rel}:999  stale entry`].join('\n'));
  try {
    logs.length = 0;
    assert.equal(run(['--allowlist', allow, 'fixtures/regexp/flagged.ts'], io), 0);
    assert.ok(logs.some((l) => /note: allowlist entry .*:999 matched no finding/.test(l)), 'stale entry noted');
  } finally { fs.unlinkSync(allow); }
});

test('repo allowlist parses and every default target still passes', () => {
  const logs = [], errs = [];
  const code = run([], { cwd: path.resolve(here, '..', '..'), log: (s) => logs.push(s), err: (s) => errs.push(s) });
  assert.equal(code, 0, errs.join('\n'));
});
